func copyFile(t *testing.T, src, dst string) {
	t.Helper()
	data, err := os.ReadFile(src)
	if err != nil {
		t.Fatalf("read %s: %v", src, err)
	}
	if err := os.WriteFile(dst, data, 0644); err != nil {
		t.Fatalf("write %s: %v", dst, err)
	}
}

// writeFile mirrors the helper in the core package tests.
func writeFile(path, content string) {
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		panic(err)
	}
}

// TestSeedSanitization proves the seed semantics: sanitization.go is written
// once when missing and never overwritten afterwards - author edits survive
// regeneration by contract.
func TestSeedSanitization(t *testing.T) {
	dir := t.TempDir()
	copyFile(t, filepath.Join("testdata", "users", "service.go"), filepath.Join(dir, "service.go"))

	seeded, err := SeedSanitization(dir)
	if err != nil {
		t.Fatalf("SeedSanitization: %v", err)
	}
	if !seeded {
		t.Fatal("expected seed to be written for a service without sanitization.go")
	}

	seededSrc, err := os.ReadFile(filepath.Join(dir, "sanitization.go"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"package users",
		"func SanitizationRules() *sanitize.FieldMaskConfig {",
		"sanitize.MaskPreserve",
	} {
		if !strings.Contains(string(seededSrc), want) {
			t.Errorf("seed missing %q:\n%s", want, seededSrc)
		}
	}
	if strings.Contains(string(seededSrc), "DO NOT EDIT") {
		t.Error("seed must be author-owned, not marked DO NOT EDIT")
	}

	// The author replaces the seed with real rules; re-seeding must be a no-op.
	authored := "package users\n\n// custom rules\nfunc SanitizationRules() *sanitize.FieldMaskConfig { return nil }\n"
	if err := os.WriteFile(filepath.Join(dir, "sanitization.go"), []byte(authored), 0644); err != nil {
		t.Fatal(err)
	}
	seeded, err = SeedSanitization(dir)
	if err != nil {
		t.Fatalf("second SeedSanitization: %v", err)
	}
	if seeded {
		t.Error("existing sanitization.go must never be overwritten")
	}
	after, err := os.ReadFile(filepath.Join(dir, "sanitization.go"))
	if err != nil {
		t.Fatal(err)
	}
	if string(after) != authored {
		t.Error("author edits to sanitization.go were clobbered")
	}
}

// TestSanitizationCollector proves discovery (only services declaring
// SanitizationRules are collected, sorted by scope, sanitize-free services
// skipped) and byte-stable regeneration.
func TestSanitizationCollector(t *testing.T) {
	// The module root carries module.go so packageName resolves the real
	// package clause (production roots always have one).
	root := t.TempDir()
	writeFile(filepath.Join(root, "module.go"), "package system\n")
	for _, pkg := range []string{"users", "audit"} {
		dir := filepath.Join(root, pkg)
		if err := os.MkdirAll(dir, 0755); err != nil {
			t.Fatal(err)
		}
		svcSrc := fmt.Sprintf("package %s\n\nimport \"github.com/asaidimu/go-anansi/v8/core/sanitize\"\n\nfunc SanitizationRules() *sanitize.FieldMaskConfig { return &sanitize.FieldMaskConfig{DefaultPolicy: sanitize.MaskPreserve} }\n", pkg)
		if err := os.WriteFile(filepath.Join(dir, "sanitization.go"), []byte(svcSrc), 0644); err != nil {
			t.Fatal(err)
		}
	}
	// A service dir without sanitization.go must be skipped.
	plain := filepath.Join(root, "tenants")
	if err := os.MkdirAll(plain, 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(plain, "service.go"), []byte("package tenants\n"), 0644); err != nil {
		t.Fatal(err)
	}

	if err := GenerateSanitizationCollector(root, "github.com/example/bench"); err != nil {
		t.Fatalf("GenerateSanitizationCollector: %v", err)
	}
	got, err := os.ReadFile(filepath.Join(root, "gen_sanitization.go"))
	if err != nil {
		t.Fatal(err)
	}
	collector := string(got)
	for _, want := range []string{
		"// Code generated by cmd/hestia service generate. DO NOT EDIT.",
		`m["audit"] = audit.SanitizationRules()`,
		`m["users"] = users.SanitizationRules()`,
		`"github.com/example/bench/audit"`,
		`"github.com/example/bench/users"`,
	} {
		if !strings.Contains(collector, want) {
			t.Errorf("collector missing %q:\n%s", want, collector)
		}
	}
	if strings.Contains(collector, "tenants") {
		t.Error("service without sanitization.go must not appear in the collector")
	}
	auditIdx, usersIdx := strings.Index(collector, `m["audit"]`), strings.Index(collector, `m["users"]`)
	if auditIdx == -1 || usersIdx == -1 || auditIdx > usersIdx {
		t.Error("collector entries must be sorted by scope for deterministic output")
	}

	// Regeneration is byte-identical.
	if err := GenerateSanitizationCollector(root, "github.com/example/bench"); err != nil {
		t.Fatalf("regenerate: %v", err)
	}
	again, err := os.ReadFile(filepath.Join(root, "gen_sanitization.go"))
	if err != nil {
		t.Fatal(err)
	}
	if string(again) != collector {
		t.Error("collector regeneration is not byte-identical")
	}
}

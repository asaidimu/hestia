// TestGenerateGolden runs Generate against the testdata/users fixture and
// compares each emitted file against its golden copy.
func TestGenerateGolden(t *testing.T) {
	src := filepath.Join("testdata", "users")
	dir := t.TempDir()
	copyFile(t, filepath.Join(src, "service.go"), filepath.Join(dir, "service.go"))

	if err := Generate(dir); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	for _, name := range []string{"registrations.go", "policies.go"} {
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatalf("read %s: %v", name, err)
		}
		golden, err := os.ReadFile(filepath.Join(src, name+".golden"))
		if err != nil {
			// First run: write the golden file.
			if err := os.WriteFile(filepath.Join(src, name+".golden"), got, 0644); err != nil {
				t.Fatalf("write golden %s: %v", name, err)
			}
			continue
		}
		if string(got) != string(golden) {
			t.Errorf("%s differs from golden\n--- want ---\n%s\n--- got ---\n%s", name, golden, got)
		}
	}
}

// TestGenerateCompiles scaffolds the fixture into a temp module, generates
// registrations.go/policies.go, and proves the package builds.
func TestGenerateCompiles(t *testing.T) {
	dir := t.TempDir()
	copyFile(t, filepath.Join("testdata", "users", "service.go"), filepath.Join(dir, "service.go"))
	writeFile(filepath.Join(dir, "go.mod"), `module github.com/example/bench

go 1.27rc1

require (
	github.com/asaidimu/go-anansi/v8 v8.5.7
	go.uber.org/zap v1.28.0
)
`)
	writeFile(filepath.Join(dir, "hestia.json"), `{
  "module": "github.com/example/bench",
  "modules": "module"
}`)

	// Copy module graph for offline resolution.
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	repoRoot := filepath.Dir(filepath.Dir(filepath.Dir(filepath.Dir(wd))))
	if data, err := os.ReadFile(filepath.Join(repoRoot, "go.sum")); err == nil {
		if err := os.WriteFile(filepath.Join(dir, "go.sum"), data, 0644); err != nil {
			t.Fatal(err)
		}
	}

	// Generated code imports hestia's abstract/dispatch packages; point the
	// temp module at the local repo.
	goMod := `module github.com/example/bench

go 1.27rc1

require (
	github.com/asaidimu/go-anansi/v8 v8.5.7
	github.com/asaidimu/hestia v0.0.0
	go.uber.org/zap v1.28.0
)

replace github.com/asaidimu/hestia => ` + repoRoot + "\n"
	writeFile(filepath.Join(dir, "go.mod"), goMod)

	if err := Generate(dir); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	tidy := exec.Command("go", "mod", "tidy")
	tidy.Dir = dir
	if out, err := tidy.CombinedOutput(); err != nil {
		t.Fatalf("go mod tidy: %v\n%s", err, out)
	}
	build := exec.Command("go", "build", "./...")
	build.Dir = dir
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("go build: %v\n%s", err, out)
	}
}


const header = "// Code generated by cmd/hestia service generate. DO NOT EDIT."

func renderRegistrations(pkg string, regs []annotate.Annotation) (string, error) {
        var b bytes.Buffer
        b.WriteString(header + "\n\n")
        fmt.Fprintf(&b, "package %s\n\n", pkg)

        // Import collection: dispatch + runtime + abstract always; context only
        // when a no-input handler needs an inline closure; plus type imports.
        // Aliased imports (e.g. usersmodel ".../users/model") are emitted with
        // their source alias so qualified references compile.
        needContext := false
        extra := map[string]string{} // import path -> alias ("" when unaliased)
        addImport := func(ref annotate.TypeRef) {
                if ref.ImportPath == "" {
                        return
                }
                extra[ref.ImportPath] = ref.Package
        }
        for _, a := range regs {
                if !a.HasInput && !a.HasStream {
                        needContext = true
                }
                addImport(a.Input)
                if a.Result == annotate.ResultDocument || a.Result == annotate.ResultDocuments {
                        addImport(a.Output)
                }
                addImport(a.OutputAttr)
        }

        var imports []string
        if needContext {
                imports = append(imports, `"context"`)
        }
        if len(regs) > 0 {
                imports = append(imports,
                        `"github.com/asaidimu/hestia/core/abstract"`,
                        `dispatch "github.com/asaidimu/hestia/core/runtime/dispatch"`,
                )
        } else {
                imports = append(imports, `"github.com/asaidimu/hestia/core/abstract"`)
        }
        for imp, alias := range extra {
                if alias != "" && alias != filepath.Base(imp) {
                        imports = append(imports, fmt.Sprintf("%s %q", alias, imp))
                } else {
                        imports = append(imports, fmt.Sprintf("%q", imp))
                }
        }
        sort.Strings(imports)
        if len(imports) > 0 {
                b.WriteString("import (\n")
                for _, i := range imports {
                        fmt.Fprintf(&b, "\t%s\n", i)
                }
                b.WriteString(")\n\n")
        }

        // The service constructor type is <Pkg>Service per the scaffold convention;
        // fall back to it when no annotations are present to name the service.
        svc := Title(pkg) + "Service"
        if len(regs) > 0 {
                svc = Title(regs[0].Service)
        }

        fmt.Fprintf(&b, "// RegisterService registers the %s service in the runtime DI\n", pkg)
        fmt.Fprintf(&b, "// container so other services can resolve it as a dependency.\n")
        fmt.Fprintf(&b, "func RegisterService(rt abstract.Container) error {\n")
        fmt.Fprintf(&b, "\treturn abstract.Register[*%s](rt, func(c abstract.Container) (*%s, error) {\n", svc, svc)
        fmt.Fprintf(&b, "\t\treturn New%s(c)\n", svc)
        b.WriteString("\t})\n}\n\n")

        fmt.Fprintf(&b, "// Registrations returns the message registrations for the %s service.\n", pkg)
        b.WriteString("func Registrations(rt abstract.Container) ([]abstract.MessageRegistration, error) {\n")
        if len(regs) == 0 {
                b.WriteString("\treturn nil, nil\n}\n")
                return b.String(), nil
        }
        fmt.Fprintf(&b, "\ts := abstract.MustResolve[*%s](rt)\n", svc)
        b.WriteString("\treturn []abstract.MessageRegistration{\n")
        for _, a := range regs {
                if err := writeRegistration(&b, a); err != nil {
                        return "", err
                }
        }
        b.WriteString("\t}, nil\n}\n")
        return b.String(), nil
}

func writeRegistration(b *bytes.Buffer, a annotate.Annotation) error {
        fmt.Fprintf(b, "\t\t{\n")
        fmt.Fprintf(b, "\t\t\tName:        %q,\n", a.MessageName)
        if a.Description != "" {
                fmt.Fprintf(b, "\t\t\tDescription: %q,\n", a.Description)
        }
        fmt.Fprintf(b, "\t\t\tIntent:      %s,\n", verbConst(a.Verb))
        fmt.Fprintf(b, "\t\t\tEnabled:     true,\n")
        if a.BootstrapSafe {
                b.WriteString("\t\t\tBootstrapSafe: true,\n")
        }
        if a.Internal {
                b.WriteString("\t\t\tInternal: true,\n")
        }
        if a.FireAndForget {
                b.WriteString("\t\t\tFireAndForget: true,\n")
        }

        // A streaming method's `<-chan dispatch.Item[TIn]` param carries the
        // item type: the parser sets HasStream with Input=TIn and HasInput=false,
        // so the Input block must key off both.
        if a.HasInput || a.HasStream {
                in, _ := qual(a.Input)
                b.WriteString("\t\t\tInput: abstract.Input{\n")
                fmt.Fprintf(b, "\t\t\t\tSchema:          dispatch.SchemaFromTypeWithTag[%s](\"input\"),\n", in)
                if a.ResourceIDField != "" {
                        fmt.Fprintf(b, "\t\t\t\tResourceIDField: %q,\n", a.ResourceIDField)
                }
                if a.HasStream {
                        b.WriteString("\t\t\t\tStreaming:       true,\n")
                }
                b.WriteString("\t\t\t},\n")
        }

        // Output is the declared wire shape: from the signature for document /
        // documents results, or from the output="Type" attribute for raw and
        // empty-result handlers that still declare one (e.g. auth's MessageOutput).
        outRef := a.Output
        if a.Result == annotate.ResultRaw || a.Result == annotate.ResultEmpty {
                // The signature's output is *abstract.Result (or absent) for these
                // kinds, which isn't a wire schema; only an explicit output= attr is.
                outRef = annotate.TypeRef{}
        }
        if a.OutputAttr.Name != "" {
                outRef = a.OutputAttr
        }
        if outRef.Name != "" {
                out, _ := qual(outRef)
                fmt.Fprintf(b, "\t\t\tOutput: dispatch.SchemaFromType[%s](),\n", out)
        }

        handler, err := handlerExpr(a)
        if err != nil {
                return err
        }
        fmt.Fprintf(b, "\t\t\tHandler:     %s,\n", handler)
        fmt.Fprintf(b, "\t\t},\n")
        return nil
}

// handlerExpr renders the dispatch adapter bound to the service method. A
// no-input empty handler can't use HandleEmpty (which binds a TIn), so it gets
// an inline closure.
func handlerExpr(a annotate.Annotation) (string, error) {
        m := "s." + a.MethodName

        switch {
        case a.HasStream:
                // Streaming input: the service method's signature is the
                // StreamHandler shape (a <-chan dispatch.Item[TIn] param), so
                // HandleInputStream binds it directly. Per-item errors arrive
                // as Item.Err — the handler owns the abort-vs-collect policy.
                in, _ := qual(a.Input)
                return fmt.Sprintf("dispatch.HandleInputStream[%s](%s)", in, m), nil
        case a.Result == annotate.ResultRaw:
                // The method returns (*abstract.Result, error) directly. dispatch.Handle
                // binds the input doc then returns whatever Result the method built, so
                // it carries fields like SessionToken that the wrap adapters drop.
                if a.HasInput {
                        in, _ := qual(a.Input)
                        return fmt.Sprintf("dispatch.Handle[%s](%s)", in, m), nil
                }
                return "func(ctx context.Context, msg abstract.Message) (*abstract.Result, error) {\n\t\t\t\treturn " + m + "(ctx, msg)\n\t\t\t}", nil
        case !a.HasInput:
                switch a.Result {
                case annotate.ResultEmpty:
                        return "func(ctx context.Context, msg abstract.Message) (*abstract.Result, error) {\n\t\t\t\tif err := " + m + "(ctx, msg); err != nil {\n\t\t\t\t\treturn nil, err\n\t\t\t\t}\n\t\t\t\treturn &abstract.Result{}, nil\n\t\t\t}", nil
                case annotate.ResultDocument:
                        return "func(ctx context.Context, msg abstract.Message) (*abstract.Result, error) {\n\t\t\t\tmodel, err := " + m + "(ctx, msg)\n\t\t\t\tif err != nil {\n\t\t\t\t\treturn nil, err\n\t\t\t\t}\n\t\t\t\tdoc, err := model.Document()\n\t\t\t\tif err != nil {\n\t\t\t\t\treturn nil, err\n\t\t\t\t}\n\t\t\t\treturn dispatch.NewDocumentResult(doc), nil\n\t\t\t}", nil
                case annotate.ResultDocuments:
                        return "func(ctx context.Context, msg abstract.Message) (*abstract.Result, error) {\n\t\t\t\tdocs, err := " + m + "(ctx, msg)\n\t\t\t\tif err != nil {\n\t\t\t\t\treturn nil, err\n\t\t\t\t}\n\t\t\t\treturn dispatch.NewDocumentsResult(docs), nil\n\t\t\t}", nil
                default:
                        return "", fmt.Errorf("unsupported result kind %s for %s", a.Result, a.MessageName)
                }
        }

        in, _ := qual(a.Input)
        switch a.Result {
        case annotate.ResultEmpty:
                return fmt.Sprintf("dispatch.HandleEmpty[%s](%s)", in, m), nil
        case annotate.ResultDocument:
                out, _ := qual(a.Output)
                if a.Output.Star {
                        out = "*" + out
                }
                return fmt.Sprintf("dispatch.HandleDocument[%s, %s](%s)", in, out, m), nil
        case annotate.ResultDocuments:
                return fmt.Sprintf("dispatch.HandleDocuments[%s](%s)", in, m), nil
        default:
                return "", fmt.Errorf("unsupported result kind %s for %s", a.Result, a.MessageName)
        }
}
func renderPolicies(pkg string, regs []annotate.Annotation) (string, error) {
        var b bytes.Buffer
        b.WriteString(header + "\n\n")
        fmt.Fprintf(&b, "package %s\n\n", pkg)

        if pkg != "policies" {
                b.WriteString("import \"github.com/asaidimu/hestia/core/system/policies\"\n\n")
        }
        binding := "policies.Binding"
        if pkg == "policies" {
                binding = "Binding"
        }
        fmt.Fprintf(&b, "// Policies returns the policy bindings for the %s service.\n", pkg)
        fmt.Fprintf(&b, "func Policies() []%s {\n", binding)
        fmt.Fprintf(&b, "\treturn []%s{\n", binding)
        for _, a := range regs {
                rule := a.Rule
                if rule == "" {
                        rule = "authenticated"
                }
                fmt.Fprintf(&b, "\t\t{Name: %q, RuleKey: %q, Description: %q},\n", a.MessageName, rule, a.Description)
        }
        b.WriteString("\t}\n}\n")
        return b.String(), nil
}

// renderCollector renders the service collector: RegisterServices registers
// every service provider into the DI container, and CollectServiceRegistrations
// resolves each service's registrations after the container has been sealed.
func renderCollector(pkg string, services []Service) (string, error) {
        var b bytes.Buffer
        b.WriteString(header + "\n\n")
        fmt.Fprintf(&b, "package %s\n\n", pkg)

        b.WriteString("import (\n")
        b.WriteString("\t\"github.com/asaidimu/hestia/core/abstract\"\n")
        for _, s := range services {
                fmt.Fprintf(&b, "\t%q\n", s.ImportPath)
        }
        b.WriteString(")\n\n")

        b.WriteString("// RegisterServices registers every service provider into the runtime DI\n")
        b.WriteString("// container. Call this during module Setup, after runtime-level providers\n")
        b.WriteString("// (persistence, logger, etc.) have been registered and before the container\n")
        b.WriteString("// is sealed by the boot phase.\n")
        b.WriteString("func RegisterServices(rt abstract.Container) error {\n")
        for _, s := range services {
                fmt.Fprintf(&b, "\tif err := %s.RegisterService(rt); err != nil {\n\t\treturn err\n\t}\n", s.Package)
        }
        b.WriteString("\treturn nil\n}\n\n")

        b.WriteString("// CollectServiceRegistrations returns all message registrations from every\n")
        b.WriteString("// service. Call this after the container has been sealed, so services can be\n")
        b.WriteString("// resolved and their registrations collected.\n")
        b.WriteString("func CollectServiceRegistrations(rt abstract.Container) ([]abstract.MessageRegistration, error) {\n")
        b.WriteString("\tvar regs []abstract.MessageRegistration\n")
        var firstService = true
        for _, s := range services {
                op := "="
                if firstService {
                        op = ":="
                        firstService = false
                }
                fmt.Fprintf(&b, "\tserviceRegs, err %s %s.Registrations(rt)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\tregs = append(regs, serviceRegs...)\n", op, s.Package)
        }
        b.WriteString("\treturn regs, nil\n}\n")
        return b.String(), nil
}

// Title capitalizes the first letter of s.
func Title(s string) string {
        if s == "" {
                return s
        }
        return strings.ToUpper(s[:1]) + s[1:]
}

func sortedKeys(m map[string]string) []string {
        keys := make([]string, 0, len(m))
        for k := range m {
                keys = append(keys, k)
        }
        sort.Strings(keys)
        return keys
}

// renderSanitizationSeed renders the sanitization.go scaffold for a service.
// The seed carries the authoring guidance (which properties need masking,
// which policies exist) so agents and humans discover the sanitization
// contract at the right place and time; the surrounding flow never overwrites
// it once written.
func renderSanitizationSeed(pkg string) string {
        var b bytes.Buffer
        fmt.Fprintf(&b, "// Sanitization rules for the %s feature.\n", pkg)
        b.WriteString("//\n")
        b.WriteString("// Scaffolded by `hestia service new` / `hestia service generate`. This file\n")
        b.WriteString("// is a seed, not a generated artifact: it is written only while missing and\n")
        b.WriteString("// is then OWNED BY THE FEATURE AUTHOR (human or coding agent). Enumerate\n")
        b.WriteString("// every sensitive property this service can emit - credentials, personal\n")
        b.WriteString("// data, confidential business fields - and give each an explicit policy.\n")
        b.WriteString("//\n")
        b.WriteString("// Policy vocabulary (sanitize.MaskedFieldPolicy):\n")
        b.WriteString("//\n")
        b.WriteString("//   - MaskRedact   - replace the value with \"***\". Default for secrets:\n")
        b.WriteString("//     password, secret, token, api key, private key, session material.\n")
        b.WriteString("//   - MaskObscure  - keep a short prefix/suffix (see ObscureConfig). For\n")
        b.WriteString("//     identifiers that must stay partly readable: email, phone, card PAN.\n")
        b.WriteString("//   - MaskHash     - short deterministic hash. For values that must remain\n")
        b.WriteString("//     correlatable across log lines without revealing them.\n")
        b.WriteString("//   - MaskPreserve - keep as-is. Safe fields only.\n")
        b.WriteString("//\n")
        b.WriteString("// Field families can be matched with regex patterns via\n")
        b.WriteString("// sanitize.MustCompilePattern(\"pattern\", policy) in the Patterns field\n")
        b.WriteString("// (e.g. \".*_token$\" or \"(?i)password.*\"). Everything not listed falls back\n")
        b.WriteString("// to DefaultPolicy - MaskPreserve keeps it verbatim.\n")
        b.WriteString("//\n")
        b.WriteString("// An empty Fields map is acceptable only while the service provably emits\n")
        b.WriteString("// no sensitive properties; revisit this file whenever inputs, outputs or\n")
        b.WriteString("// log shapes change. The generated collector (gen_sanitization.go)\n")
        b.WriteString("// registers this config under this feature's scope and the runtime\n")
        b.WriteString("// sanitization dispatcher applies it to responses, logs and streams.\n")
        fmt.Fprintf(&b, "package %s\n\n", pkg)
        b.WriteString("import \"github.com/asaidimu/go-anansi/v8/core/sanitize\"\n\n")
        b.WriteString("func SanitizationRules() *sanitize.FieldMaskConfig {\n")
        b.WriteString("\treturn &sanitize.FieldMaskConfig{\n")
        b.WriteString("\t\tDefaultPolicy: sanitize.MaskPreserve,\n")
        b.WriteString("\t\tFields: map[string]sanitize.MaskedFieldPolicy{\n")
        b.WriteString("\t\t\t// \"password\": sanitize.MaskRedact,\n")
        b.WriteString("\t\t\t// \"email\":    sanitize.MaskObscure,\n")
        b.WriteString("\t\t},\n")
        b.WriteString("\t}\n")
        b.WriteString("}\n")
        return b.String()
}

// renderSanitizationCollector renders the module's sanitization aggregator:
// allSanitizationRules maps each feature scope (the second segment of a
// message name, e.g. "system:users:user:get" -> "users") to that feature's
// declared FieldMaskConfig. The system module registers every entry with
// sanitize.Registry() during Setup.
func renderSanitizationCollector(pkg string, services []Service) (string, error) {
        var b bytes.Buffer
        b.WriteString(header + "\n\n")
        fmt.Fprintf(&b, "package %s\n\n", pkg)

        b.WriteString("import \"github.com/asaidimu/go-anansi/v8/core/sanitize\"\n\n")

        if len(services) > 0 {
                b.WriteString("import (\n")
                for _, s := range services {
                        fmt.Fprintf(&b, "\t%q\n", s.ImportPath)
                }
                b.WriteString(")\n\n")
        }

        b.WriteString("// allSanitizationRules aggregates every feature's sanitization rules,\n")
        b.WriteString("// keyed by feature scope. A feature appears here when its package declares\n")
        b.WriteString("// SanitizationRules() in sanitization.go; add rules for sensitive\n")
        b.WriteString("// properties by editing that file - never this generated collector.\n")
        b.WriteString("var allSanitizationRules = func() map[string]*sanitize.FieldMaskConfig {\n")
        b.WriteString("\tm := make(map[string]*sanitize.FieldMaskConfig)\n")
        for _, s := range services {
                fmt.Fprintf(&b, "\tm[%q] = %s.SanitizationRules()\n", s.Package, s.Package)
        }
        b.WriteString("\treturn m\n")
        b.WriteString("}()\n")
        return b.String(), nil
}
